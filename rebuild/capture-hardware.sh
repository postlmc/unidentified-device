#!/usr/bin/env bash
# Capture this machine's disk and filesystem identity into rebuild/hardware.env.
# Reads the live system rather than assuming a layout, so it is correct both before
# and after the drive 2 rework. The output is gitignored: it identifies specific hardware.
set -euo pipefail

out="${1:-rebuild/hardware.env}"

# findmnt reports btrfs sources as /dev/xxx[/subvol]; strip the bracketed part.
dev_of()    { findmnt -no SOURCE "$1" 2>/dev/null | sed 's/\[.*\]//'; }
uuid_of()   { local d; d=$(dev_of "$1") && [ -n "$d" ] && lsblk -no UUID "$d" 2>/dev/null | head -1; }
label_of()  { local d; d=$(dev_of "$1") && [ -n "$d" ] && lsblk -no LABEL "$d" 2>/dev/null | head -1; }
subvol_of() { findmnt -no OPTIONS "$1" 2>/dev/null | tr ',' '\n' | sed -n 's|^subvol=/||p'; }

{
    echo "# Generated by rebuild/capture-hardware.sh on $(date -u +%Y-%m-%dT%H:%M:%SZ)"
    echo

    echo "# --- OS drive: wiped and reinstalled on rebuild ---"
    echo "OS_FS_UUID=$(uuid_of /sysroot)"
    echo "OS_FS_LABEL=$(label_of /sysroot)"
    echo "OS_ESP_UUID=$(uuid_of /boot/efi)"
    echo "OS_BOOT_UUID=$(uuid_of /boot)"
    echo "OS_ROOT_SUBVOL=$(subvol_of /sysroot)"
    echo "OS_VAR_SUBVOL=$(subvol_of /var)"
    echo

    echo "# --- Persistent drive: the installer never touches this ---"
    if [ "$(dev_of /var/home)" = "$(dev_of /sysroot)" ]; then
        echo "# NOTE: /home is still on the OS drive; the drive 2 rework has not been done yet."
    fi
    echo "PERSIST_FS_UUID=$(uuid_of /var/home)"
    echo "PERSIST_FS_LABEL=$(label_of /var/home)"
    echo "PERSIST_HOME_SUBVOL=$(subvol_of /var/home)"
    if findmnt -no TARGET /var/mnt/games >/dev/null 2>&1; then
        echo "PERSIST_GAMES_SUBVOL=$(subvol_of /var/mnt/games)"
    else
        echo "# PERSIST_GAMES_SUBVOL=  # not mounted yet"
    fi
    echo

    echo "# --- Image ---"
    echo "IMAGE_REF=ghcr.io/postlmc/unidentified-device:latest"
} > "$out"

echo "Wrote $out"
